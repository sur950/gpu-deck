#!/usr/bin/env python3
"""
env.md <-> settings <-> .env.example reconciliation.

The settings classes in ``apps/fastapi/app/core/settings/*.py`` are the source
of truth for what the Python processes read. This script fails (exit 1) when:

  1. a settings field (or one of its accepted alias names) has no row in
     ``libs/contracts/env.md``;
  2. an env.md row read by a Python process (Proc column ``A``, ``L``, ``J`` or
     ``H``) names a variable that is neither a settings field nor an alias
     (rows only read by the web app ``W``, the node agent ``N`` or by the
     deployment tooling ``I`` — compose, Helm, scripts — are exempt);
  3. an env.md default differs from the settings default (rows whose default
     cell is a single literal; ``*(empty)*`` must match an empty/None default);
  4. ``.env.example`` (repo root and ``apps/fastapi``) is not exactly what
     ``--write`` generates from the settings classes, or does not parse.

    apps/fastapi/venv/bin/python scripts/check_env_docs.py          # check (CI)
    apps/fastapi/venv/bin/python scripts/check_env_docs.py --write  # regenerate both
        .env.example files and append rows for undocumented settings to env.md

The .env.example files are generated: edit field descriptions/defaults in the
settings classes (or EXAMPLE_VALUES below), then run ``--write``.
"""


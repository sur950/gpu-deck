# ---------------------------------------------------------------------------
# settings introspection
# ---------------------------------------------------------------------------


COMPUTED = object()


class Field_:
    def __init__(self, name, module, info):
        self.name = name
        self.module = module
        self.info = info
        self.aliases: List[str] = []
        alias = info.validation_alias
        choices = getattr(alias, "choices", None)
        if choices:
            self.aliases = [c for c in choices if isinstance(c, str) and c != name]
        elif isinstance(alias, str) and alias != name:
            self.aliases = [alias]

    @property
    def required(self) -> bool:
        return self.info.is_required()

    @property
    def default(self) -> Any:
        if self.required:
            return None
        if self.info.default_factory is not None:
            return COMPUTED  # host/pid/time dependent: never written or compared
        return self.info.default

    @property
    def description(self) -> str:
        return " ".join((self.info.description or "").split())


def load_fields() -> List[Field_]:
    sys.path.insert(0, str(FASTAPI))
    os.chdir(FASTAPI)
    import logging

    logging.disable(logging.CRITICAL)
    from app.core.settings import discover_settings_classes

    out = []
    for cls in discover_settings_classes():
        module = cls.__module__.rsplit(".", 1)[-1]
        for name, info in cls.model_fields.items():
            out.append(Field_(name, module, info))
    return out


def render_value(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, tuple, set)):
        return ",".join(str(v) for v in value)
    if isinstance(value, dict):
        import json

        return json.dumps(value, separators=(",", ":"))
    text = str(value)
    if text == "" or re.search(r"[\s#\"']", text):
        return '"' + text.replace('"', '\\"') + '"'
    return text


# ---------------------------------------------------------------------------
# .env.example generation
# ---------------------------------------------------------------------------


def generate_example(fields: List[Field_], where: str, with_web: bool) -> str:
    lines = [HEADER.format(where=where)]
    by_module: Dict[str, List[Field_]] = {}
    for f in fields:
        by_module.setdefault(f.module, []).append(f)
    order = [m for m in MODULES if m in by_module] + sorted(set(by_module) - set(MODULES))
    for module in order:
        title = MODULES.get(module, (module.capitalize(), "", ""))[0]
        lines.append(f"\n# ---------- {title} (app/core/settings/{module}.py) ----------")
        for f in by_module[module]:
            if f.description:
                lines.append(f"# {f.description}")
            if f.aliases:
                lines.append(f"#   (also accepted: {', '.join(f.aliases)})")
            if f.name in EXAMPLE_VALUES:
                lines.append(f"{f.name}={EXAMPLE_VALUES[f.name]}")
            elif f.required:
                lines.append(f"{f.name}=CHANGE-ME")
            elif f.default is COMPUTED:
                lines.append(f"# {f.name}=   (default computed at startup)")
            elif f.default is None or f.default == "":
                lines.append(f"# {f.name}=")
            else:
                lines.append(f"{f.name}={render_value(f.default)}")
    text = "\n".join(lines) + "\n"
    if with_web:
        text += WEB_SECTION
    return text


def example_errors(fields: List[Field_]) -> List[str]:
    errors = []
    for path in EXAMPLES:
        root = path.parent == ROOT
        expected = generate_example(fields, "repo root" if root else "apps/fastapi", root)
        if not path.is_file() or path.read_text() != expected:
            errors.append(
                f"{path.relative_to(ROOT)} is stale — run scripts/check_env_docs.py --write"
            )
    # The generated file must load into the settings class.
    # Placeholders are rejected by the validators on purpose; swap in valid values.
    from cryptography.fernet import Fernet

    valid = {
        "SECRET_KEY": "0" * 64,
        "VAULT_KEYS": Fernet.generate_key().decode(),
        "ADMIN_PASSWORD": "check-env-docs-Password-1",
    }
    expected = "\n".join(
        (
            f"{line.split('=', 1)[0]}={valid[line.split('=', 1)[0]]}"
            if line.split("=", 1)[0] in valid
            else line
        )
        for line in generate_example(fields, "apps/fastapi", False).splitlines()
    )
    with tempfile.NamedTemporaryFile("w", suffix=".env", delete=False) as tmp:
        tmp.write(expected)
    try:
        from app.core.settings import Settings

        Settings(_env_file=tmp.name)
    except Exception as exc:  # noqa: BLE001
        errors.append(f"generated .env.example does not parse: {exc}")
    finally:
        os.unlink(tmp.name)
    return errors


# ---------------------------------------------------------------------------
# env.md
# ---------------------------------------------------------------------------


class Row:
    def __init__(self, section: str, names: List[str], default: str, procs: set, line_no: int):
        self.section = section
        self.names = names
        self.default = default
        self.procs = procs
        self.line_no = line_no


def parse_env_md(text: str) -> List[Row]:
    rows = []
    section = ""
    for no, line in enumerate(text.splitlines(), 1):
        if line.startswith("## "):
            section = line[3:].split(".")[0].strip()
            continue
        if not line.startswith("| `"):
            continue
        cols = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cols) < 3:
            continue
        names = re.findall(r"`([A-Z][A-Z0-9_]+)`", cols[0])
        procs = set(re.findall(r"\b[A-Z]\b", cols[2]))
        if "all" in cols[2]:
            procs |= {"A", "L", "J"}
        rows.append(Row(section, names, cols[1], procs, no))
    return rows


def _literal(cell: str, count: int) -> Optional[List[str]]:
    """Split a default cell into ``count`` literals, or None when it is prose."""
    cell = cell.strip()
    if cell in ("*(empty)*", "", "—", "-"):
        return [""] * count
    parts = [p.strip() for p in cell.split(" / ")] if count > 1 else [cell]
    if len(parts) != count:
        return None
    out = []
    for p in parts:
        if p == "*(empty)*":
            out.append("")
            continue
        m = re.fullmatch(r"`([^`]*)`", p)
        if not m:
            return None
        out.append(m.group(1))
    return out


def _same(doc: str, value: Any) -> bool:
    if value is None or value == "":
        return doc in ("", "none", "null")
    if isinstance(value, bool):
        return doc.lower() == ("true" if value else "false")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        try:
            return float(doc.replace("_", "")) == float(value)
        except ValueError:
            return False
    if isinstance(value, (list, tuple, set)):
        return [d.strip() for d in doc.split(",") if d.strip()] == [str(v) for v in value]
    return doc.strip('"') == str(value)


def env_md_errors(fields: List[Field_], rows: List[Row]) -> Tuple[List[str], List[Field_]]:
    errors: List[str] = []
    by_name: Dict[str, Field_] = {}
    for f in fields:
        by_name[f.name] = f
        for a in f.aliases:
            by_name[a] = f
    documented = {n for r in rows for n in r.names}
    missing = [f for f in fields if f.name not in documented and not (set(f.aliases) & documented)]
    for f in missing:
        errors.append(f"env.md: settings field {f.name} ({f.module}.py) is not documented")
    for r in rows:
        if r.section == "13" or not (r.procs & PY_PROCS):
            continue
        for n in r.names:
            if n not in by_name:
                errors.append(
                    f"env.md:{r.line_no}: {n} is read by {''.join(sorted(r.procs))} per env.md "
                    "but no settings field/alias exists (implement it, fix the name, or mark "
                    "the row I = deployment tooling only)"
                )
        literals = _literal(r.default, len(r.names))
        if literals is None:
            continue
        for n, doc in zip(r.names, literals):
            f = by_name.get(n)
            if f is None or f.required or f.default is COMPUTED:
                continue
            if not _same(doc, f.default):
                errors.append(
                    f"env.md:{r.line_no}: default of {n} is `{doc}` but settings say "
                    f"{render_value(f.default) or '(empty)'}"
                )
    return errors, missing


def append_rows(text: str, missing: List[Field_]) -> str:
    """Insert one row per undocumented field at the end of its section's table."""
    lines = text.splitlines()
    for f in missing:
        section = MODULES.get(f.module, ("", "15", "A J"))[1]
        procs = MODULES.get(f.module, ("", "15", "A J"))[2]
        default = "" if f.default is COMPUTED else render_value(f.default).strip('"')
        cell = f"`{default}`" if default else "*(empty)*"
        desc = f.description.replace("|", "\\|")
        if f.aliases:
            desc += f" (also accepted: {', '.join('`' + a + '`' for a in f.aliases)})"
        row = f"| `{f.name}` | {cell} | {procs} | {desc} |"
        start = next((i for i, ln in enumerate(lines) if re.match(rf"^## {section}\.", ln)), None)
        if start is None:
            insert_at = next(
                (
                    i
                    for i, ln in enumerate(lines)
                    if re.match(r"^## 1[3-9]\.", ln) and int(ln[3:5]) > int(section)
                ),
                len(lines),
            )
            block = [
                "",
                NEW_SECTIONS[section],
                "",
                "| Name | Default | Proc | Description |",
                "| --- | --- | --- | --- |",
                row,
                "",
            ]
            lines[insert_at:insert_at] = block
            continue
        i = start + 1
        last_row = None
        while i < len(lines) and not lines[i].startswith("## "):
            if lines[i].startswith("| "):
                last_row = i
            i += 1
        pos = (last_row + 1) if last_row is not None else i
        lines.insert(pos, row)
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="regenerate files instead of checking")
    args = parser.parse_args()

    fields = load_fields()
    if args.write:
        for path in EXAMPLES:
            root = path.parent == ROOT
            path.write_text(generate_example(fields, "repo root" if root else "apps/fastapi", root))
        text = ENV_MD.read_text()
        _, missing = env_md_errors(fields, parse_env_md(text))
        if missing:
            ENV_MD.write_text(append_rows(text, missing))
        print(f"wrote {len(EXAMPLES)} .env.example files; env.md +{len(missing)} rows")

    errors, _ = env_md_errors(fields, parse_env_md(ENV_MD.read_text()))
    errors += example_errors(fields)
    for e in errors:
        print(f"ERROR {e}")
    if errors:
        print(f"{len(errors)} env drift error(s)")
        return 1
    print(f"OK: {len(fields)} settings fields documented in env.md and .env.example")
    return 0


if __name__ == "__main__":
    sys.exit(main())

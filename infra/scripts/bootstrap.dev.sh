# ---------- service client certificates (API layer + control plane -> node proxies) ----------

ensure_service_certs() {
  print_step "Service client certificates (internal CA)"
  local dir="$RUN_DIR/certs"
  mkdir -p "$dir"; chmod 700 "$dir"
  # The internal CA lives in the database: after `deps reset` (or a restored dump) it is a new
  # CA, and certificates issued by the old one fail every mTLS call to the node proxies
  # (CERTIFICATE_VERIFY_FAILED). Fetch the current CA and re-issue what it did not sign.
  local current_ca="$dir/.current-ca.pem"
  rm -f "$current_ca"
  (cd "$FASTAPI_DIR" && "$VENV/bin/python" - "$current_ca" <<'PY'
import asyncio, sys
from app.db.postgres.connection import get_session_maker
from app.services.pki.service import PkiService

async def run():
    async with get_session_maker()() as session:
        ca = await PkiService.from_session(session).ca_certificate()
        await session.commit()
    with open(sys.argv[1], "w") as fh:
        fh.write(ca["certificate_pem"])

asyncio.run(run())
PY
  ) >/dev/null 2>&1 || print_info "could not read the internal CA; only certificate expiry is checked"
  for kind in api_layer control_plane; do
    if [ -s "$dir/$kind.crt" ] && [ -s "$dir/$kind.key" ] && \
       openssl x509 -checkend 86400 -noout -in "$dir/$kind.crt" >/dev/null 2>&1; then
      if [ ! -s "$current_ca" ] || \
         openssl verify -CAfile "$current_ca" "$dir/$kind.crt" >/dev/null 2>&1; then
        print_success "$kind certificate present ($dir/$kind.crt)"
        continue
      fi
      print_info "$kind certificate was issued by another CA (database reset?): re-issuing"
    fi
    (cd "$FASTAPI_DIR" && "$VENV/bin/python" - "$kind" "$dir" <<'PY'
import asyncio, os, sys
from app.db.postgres.connection import get_session_maker
from app.services.pki.service import PkiService

kind, out = sys.argv[1], sys.argv[2]

async def run():
    async with get_session_maker()() as session:
        issued = await PkiService.from_session(session).issue_service_certificate(kind)
        await session.commit()
    for name, body, mode in (
        (f"{kind}.crt", issued["certificate_pem"], 0o644),
        (f"{kind}.key", issued["private_key_pem"], 0o600),
        ("ca.pem", issued["ca_bundle_pem"], 0o644),
    ):
        path = os.path.join(out, name)
        with open(path, "w") as fh:
            fh.write(body)
        os.chmod(path, mode)

asyncio.run(run())
PY
    ) >/dev/null 2>&1 && print_success "$kind certificate issued" || print_error "could not issue $kind certificate"
  done
  rm -f "$current_ca"
  _set_env API_LAYER_CLIENT_CERT_PATH "$dir/api_layer.crt"
  _set_env API_LAYER_CLIENT_KEY_PATH "$dir/api_layer.key"
  _set_env API_LAYER_CA_BUNDLE_PATH "$dir/ca.pem"
  _set_env CONTROL_PLANE_CLIENT_CERT_PATH "$dir/control_plane.crt"
  _set_env CONTROL_PLANE_CLIENT_KEY_PATH "$dir/control_plane.key"
  load_env
}


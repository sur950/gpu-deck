# seed-demo [--reset | --live | --days N ...] (args go to seed_demo.py). The demo seed is a
# maintainer-only, git-ignored tool (not part of the public repository); in a public checkout
# this command only explains that it is unavailable.
cmd_seed_demo() {
  local script="app/db/postgres/scripts/seed_demo.py"
  if [ ! -f "$FASTAPI_DIR/$script" ] || [ ! -d "$FASTAPI_DIR/app/db/postgres/demo" ]; then
    print_error "demo seed not available in this checkout (it is a local-only maintainer tool)"
    print_info "  use '$0 seed' for the admin account, then add nodes from Nodes > Add node"
    exit 1
  fi
  load_env
  case "${1:-}" in
    --reset) print_step "Removing the demo data (rows marked demo only)" ;;
    --live)  print_step "Demo live mode: heartbeats + metrics for the demo nodes (Ctrl-C stops)" ;;
    *)       print_step "Seeding demo data (replaces any previous demo rows)" ;;
  esac
  (cd "$FASTAPI_DIR" && "$VENV/bin/python" "$script" "$@")
  [ "${1:-}" = "--live" ] || print_success "seed-demo finished"
}

cmd_stop() {
  load_env
  stop_all
  if [ "${1:-}" = "--deps" ]; then
    deps_down
  else
    print_info "  dependency containers keep running (stop them with: $0 stop --deps or $0 deps down)"
  fi
}

cmd_restart() {
  load_env
  if [ -n "${1:-}" ]; then
    stop_proc "$1"; start_service "$1"
  else
    stop_all; start_all
  fi
}

cmd_status() {
  load_env
  print_step "Process status"
  for svc in $SERVICES; do
    if is_running "$svc"; then
      echo -e "  - ${svc}: ${GREEN}running${NC} (pid $(cat "$(pid_file "$svc")"))"
    else
      echo -e "  - ${svc}: ${RED}stopped${NC}"
    fi
  done
  print_step "Listening ports"
  for p in "$PORT" "$API_LAYER_PORT" "$AGENT_HUB_PORT" "$WEB_PORT"; do
    if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then
      echo -e "  - :${p} ${GREEN}listening${NC}"
    else
      echo -e "  - :${p} ${RED}free${NC}"
    fi
  done
  deps_status
}

cmd_health() {
  load_env
  print_step "Health"
  local out
  out=$(curl -sf "http://localhost:${PORT}/api/v1/health" 2>/dev/null) && \
    echo -e "  - admin-api: ${GREEN}$(echo "$out" | sed -E 's/.*"status": ?"([a-z]+)".*/\1/')${NC}" || \
    echo -e "  - admin-api: ${RED}unreachable${NC}"
  out=$(curl -sf "http://localhost:${API_LAYER_PORT}/health" 2>/dev/null) && \
    echo -e "  - api-layer: ${GREEN}$(echo "$out" | sed -E 's/.*"status": ?"([a-z]+)".*/\1/')${NC}" || \
    echo -e "  - api-layer: ${RED}unreachable${NC}"
  out=$(curl -sfk "https://localhost:${AGENT_HUB_PORT}/health" 2>/dev/null) && \
    echo -e "  - agent-hub: ${GREEN}$(echo "$out" | sed -E 's/.*"status": ?"([a-z]+)".*/\1/')${NC}" || \
    echo -e "  - agent-hub: ${RED}unreachable${NC}"
  for svc in worker scheduler; do
    is_running "$svc" && echo -e "  - ${svc}: ${GREEN}running${NC}" || echo -e "  - ${svc}: ${RED}stopped${NC}"
  done
  local cid status
  for svc in postgres redis; do
    cid=$( (docker info >/dev/null 2>&1 && [ -f "$DEPS_ENV" ] && dc ps -q "$svc") 2>/dev/null || true)
    status=$( [ -n "$cid" ] && docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo "not running")
    [ "$status" = "healthy" ] && echo -e "  - ${svc}: ${GREEN}${status}${NC}" || echo -e "  - ${svc}: ${RED}${status}${NC}"
  done
}

cmd_logs() {
  local svc="${1:-}"
  case "$svc" in
    postgres|redis|caddy) dc logs --tail "$TAIL_LINES" -f "$svc"; return ;;
  esac
  if [ -n "$svc" ]; then
    tail -n "$TAIL_LINES" -f "$LOG_DIR/$svc.log"
  else
    tail -n "$TAIL_LINES" -f "$LOG_DIR"/*.log
  fi
}

cmd_urls() { load_env; show_urls; }

cmd_verify() {
  load_env
  print_step "Verifying endpoints"
  local base="http://localhost:${PORT}" sbase="http://localhost:${API_LAYER_PORT}" status
  check() {  # check LABEL URL EXPECTED_CODES
    status=$(curl -s -o /dev/null -w "%{http_code}" "$2")
    if echo "$3" | grep -qw "$status"; then
      print_success "$1 (HTTP ${status})"
    else
      print_error "$1: unexpected HTTP ${status}"
    fi
  }
  check "admin  /"                   "$base/"                        "200"
  check "admin  /api/v1/health"      "$base/api/v1/health"           "200"
  check "admin  /metrics"            "$base/metrics"                 "200"
  check "admin  /api/v1/health/live" "$base/api/v1/health/live"      "200"
  check "serving /"                  "$sbase/"                       "200"
  check "serving /health"            "$sbase/health"                 "200"
  check "serving /metrics"           "$sbase/metrics"                "200"
  check "serving /v1/models"         "$sbase/v1/models"              "200 401 404"
  check "serving /api/tags"          "$sbase/api/tags"               "200 401 404"
  status=$(curl -sk -o /dev/null -w "%{http_code}" "https://localhost:${AGENT_HUB_PORT}/health")
  [ "$status" = "200" ] && print_success "hub    /health (HTTP 200)" || print_error "hub    /health: unexpected HTTP ${status}"
  print_success "Verification complete"
}

cmd_caddy() {
  case "${1:-up}" in
    up)   ensure_proxy ;;
    down) require_docker; ensure_deps_env; dc stop caddy && dc rm -f caddy >/dev/null && print_success "caddy stopped" ;;
    *) print_error "Unknown caddy command: $1 (up|down)"; exit 1 ;;
  esac
}

usage() {
  local text
  text=$(cat <<EOF

${BLUE}Usage:${NC}
  ./infra/scripts/bootstrap.dev.sh [command] [args]

${BLUE}Commands:${NC}
  bootstrap         Start deps (Docker), write .env connection values, venv, migrate, seed, start all (default)
  deps up           Start Postgres + Redis containers, wait until healthy (creates infra/docker/.env)
  deps down         Stop and remove the dependency containers (data volumes are kept)
  deps status       Show the dependency containers
  deps reset [--yes] Delete the dependency volumes (all dev data) and start fresh
  seed              Seed/rotate the admin from .env
  stop [--deps]     Stop all app processes; --deps also stops the dependency containers
  restart [svc]     Restart all or one of: ${SERVICES}
  status            Process, port and dependency status
  health            Curl the health endpoints, dependency health
  logs [svc]        Tail logs: an app process, or postgres|redis|caddy (TAIL_LINES sets the line count)
  urls              Print URLs
  verify            Smoke-test endpoints
  caddy [up|down]   Optional HTTPS proxy (https://gpu-deck*.localhost:58443, compose profile proxy)
  certs             Issue the API-layer / control-plane client certs (internal CA) into .run/certs
  help              Show this help

${BLUE}Environment:${NC}
  WITH_PROXY=1      bootstrap also starts the Caddy proxy
  ADMIN_PASSWORD    initial admin password written to a fresh .env

${BLUE}Requirements:${NC} Docker with the compose plugin, uv, curl, lsof, openssl; pnpm for the web UI.

EOF
)
  echo -e "$text\n"
}

main() {
  local cmd="${1:-bootstrap}"
  shift || true
  case "$cmd" in
    bootstrap)       cmd_bootstrap "$@";;
    deps)            cmd_deps "$@";;
    seed)            cmd_seed "$@";;
    seed-demo)       cmd_seed_demo "$@";;
    stop)            cmd_stop "$@";;
    restart)         cmd_restart "$@";;
    status)          cmd_status "$@";;
    health)          cmd_health "$@";;
    logs)            cmd_logs "$@";;
    urls)            cmd_urls "$@";;
    verify)          cmd_verify "$@";;
    caddy)           cmd_caddy "$@";;
    certs)           load_env; ensure_service_certs;;
    start)           load_env; start_all;;
    help|--help|-h)  usage;;
    *) print_error "Unknown command: $cmd"; usage; exit 1;;
  esac
}

main "$@"

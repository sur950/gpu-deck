# ---------- processes ----------

pid_file() { echo "$RUN_DIR/$1.pid"; }

proc_marker() {  # a substring of the service's command line (guards against pid reuse after a reboot)
  case "$1" in
    admin-api) echo "app.main:app" ;;
    api-layer) echo "app.api_layer_main" ;;
    agent-hub) echo "app.agent_hub_main" ;;
    worker)    echo "celery" ;;
    scheduler) echo "app.workers.scheduler" ;;
    web)       echo "pnpm" ;;
    *)         echo "" ;;
  esac
}

is_running() {
  local pf pid
  pf=$(pid_file "$1")
  [ -f "$pf" ] || return 1
  pid=$(cat "$pf")
  kill -0 "$pid" 2>/dev/null || return 1
  ps -o command= -p "$pid" 2>/dev/null | grep -qF -- "$(proc_marker "$1")"
}

start_proc() {  # start_proc NAME DIR COMMAND...
  local name="$1" dir="$2"; shift 2
  mkdir -p "$LOG_DIR"
  if is_running "$name"; then
    print_info "  $name already running (pid $(cat "$(pid_file "$name")"))"
    return
  fi
  # Redirect at the subshell level and exec, so the background job holds no
  # inherited stdout/stderr pipe (otherwise `bootstrap.dev.sh ... | grep` hangs)
  # and $! is the real server pid.
  (cd "$dir" && exec nohup "$@") < /dev/null > "$LOG_DIR/$name.log" 2>&1 &
  echo $! > "$(pid_file "$name")"
  sleep 0.5
  if is_running "$name"; then
    print_success "$name started (pid $(cat "$(pid_file "$name")"))"
  else
    print_error "$name failed to start — see $LOG_DIR/$name.log"
  fi
}

stop_proc() {
  local name="$1" pf pid
  pf=$(pid_file "$name")
  [ -f "$pf" ] || return 0
  pid=$(cat "$pf")
  if is_running "$name"; then
    pkill -TERM -P "$pid" 2>/dev/null || true
    kill -TERM "$pid" 2>/dev/null || true
    for _ in $(seq 1 20); do
      kill -0 "$pid" 2>/dev/null || break
      sleep 0.5
    done
    kill -0 "$pid" 2>/dev/null && kill -KILL "$pid" 2>/dev/null || true
    print_success "$name stopped"
  fi
  rm -f "$pf"
}

celery_queues() {
  (cd "$FASTAPI_DIR" && "$VENV/bin/python" -c "from app.workers.celery_app import queue_names; print(','.join(queue_names()))" 2>/dev/null | tail -1)
}

start_service() {
  case "$1" in
    admin-api)
      # --timeout-graceful-shutdown: a reload / restart never waits on open SSE streams
      # (/live/events, /logs/stream) for more than a few seconds.
      start_proc admin-api "$FASTAPI_DIR" "$VENV/bin/uvicorn" app.main:app --host 127.0.0.1 --port "$PORT" --reload --reload-dir app --timeout-graceful-shutdown 5 ;;
    api-layer)
      start_proc api-layer "$FASTAPI_DIR" "$VENV/bin/uvicorn" app.api_layer_main:app --host 127.0.0.1 --port "$API_LAYER_PORT" --reload --reload-dir app --timeout-graceful-shutdown 30 ;;
    agent-hub)
      # Own process (mTLS, TLS 1.3, client certs optional for the join POST);
      # TLS material is materialised from the vault at start.
      start_proc agent-hub "$FASTAPI_DIR" "$VENV/bin/python" -m app.agent_hub_main ;;
    worker)
      # macOS: billiard spawns pool children and Celery's prefork pool breaks under
      # spawn ("not enough values to unpack (expected 3, got 0)"). Threads are fine
      # for our I/O-bound tasks; Linux/Docker keeps the default prefork pool.
      local pool_args=()
      [ "$(uname -s)" = "Darwin" ] && pool_args=(--pool=threads --concurrency=8)
      start_proc worker "$FASTAPI_DIR" "$VENV/bin/celery" -A app.workers.celery_app worker --beat --loglevel=info -Q "$(celery_queues)" "${pool_args[@]}" ;;
    scheduler)
      start_proc scheduler "$FASTAPI_DIR" "$VENV/bin/python" -m app.workers.scheduler ;;
    web)
      if [ -f "$WEB_DIR/package.json" ]; then
        start_proc web "$ROOT_DIR" pnpm --filter web dev
      else
        print_info "  web: apps/web not present yet — skipped"
      fi ;;
    *) print_error "unknown service: $1"; return 1 ;;
  esac
}

start_all() {
  print_step "Starting processes"
  for svc in $SERVICES; do start_service "$svc"; done
}

stop_all() {
  print_step "Stopping processes"
  for svc in $SERVICES; do stop_proc "$svc"; done
}


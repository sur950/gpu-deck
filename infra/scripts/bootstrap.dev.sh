#!/bin/bash

# ==========================================
# GPU Deck — Dev Orchestration Script
#
# Postgres and Redis (and an optional Caddy HTTPS proxy) run in Docker from
# infra/docker/docker-compose.deps.yml (compose project `gpu-deck-deps`); any
# Docker engine with `docker compose` works (OrbStack, Docker Desktop, Colima,
# Linux). App processes run from the apps/fastapi venv and are tracked with
# pid files under apps/fastapi/.run/.
#
#   ./infra/scripts/bootstrap.dev.sh [bootstrap|deps|seed|stop|restart|status|health|logs|urls|verify|caddy|certs|help]
# ==========================================

set -e

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
FASTAPI_DIR="$ROOT_DIR/apps/fastapi"
WEB_DIR="$ROOT_DIR/apps/web"
ENV_FILE="$FASTAPI_DIR/.env"
RUN_DIR="$FASTAPI_DIR/.run"
LOG_DIR="$RUN_DIR/logs"
VENV="$FASTAPI_DIR/venv"
TAIL_LINES="${TAIL_LINES:-200}"

# Docker dependencies (Postgres, Redis, optional Caddy)
DEPS_COMPOSE="$ROOT_DIR/infra/docker/docker-compose.deps.yml"
DEPS_ENV="$ROOT_DIR/infra/docker/.env"
REDIS_PREFIX="gpu-deck"

# Default ports (overridden by .env)
PORT=8180
API_LAYER_PORT=8181
AGENT_HUB_PORT=8443
WEB_PORT=3180

SERVICES="admin-api api-layer agent-hub worker scheduler web"

# Celery's pool/beat children are spawned (macOS) and do not inherit the
# parent's cwd on sys.path; make the app package importable everywhere.
export PYTHONPATH="$FASTAPI_DIR${PYTHONPATH:+:$PYTHONPATH}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

print_step()    { echo -e "\n${YELLOW}>>> $1${NC}\n"; }
print_success() { echo -e "${GREEN}✓ $1${NC}"; }
print_error()   { echo -e "${RED}✗ $1${NC}"; }
print_info()    { echo -e "${BLUE}$1${NC}"; }

echo -e "${BLUE}=========================================${NC}"
echo -e "${BLUE}GPU Deck — Development Environment${NC}"
echo -e "${BLUE}=========================================${NC}"

require_tools() {
  for tool in docker uv curl lsof openssl; do
    command -v "$tool" >/dev/null 2>&1 || { print_error "'$tool' not found on PATH"; exit 1; }
  done
  require_docker
}

require_docker() {
  command -v docker >/dev/null 2>&1 || { print_error "'docker' not found on PATH"; exit 1; }
  docker compose version >/dev/null 2>&1 || { print_error "'docker compose' (v2) is not available"; exit 1; }
  docker info >/dev/null 2>&1 || { print_error "the Docker engine is not running (start OrbStack / Docker Desktop / Colima)"; exit 1; }
}

load_env() {
  if [ -f "$ENV_FILE" ]; then
    set -a
    # shellcheck source=/dev/null
    source "$ENV_FILE"
    set +a
  fi
}

# ---------- Docker dependencies ----------

dc() {  # docker compose against the deps file (profile `proxy` included so down/ps see Caddy)
  docker compose -f "$DEPS_COMPOSE" --env-file "$DEPS_ENV" --profile proxy "$@"
}

_file_get() {  # _file_get FILE KEY  -> value of KEY= (last one wins), empty if absent
  [ -f "$1" ] || return 0
  grep -E "^$2=" "$1" | tail -1 | cut -d= -f2-
}

deps_get() { _file_get "$DEPS_ENV" "$1"; }

_file_set() {  # _file_set FILE KEY VALUE  (replace in place or append)
  local file="$1" key="$2" value="$3"
  if grep -qE "^${key}=" "$file"; then
    # use a control character as sed delimiter; values may contain / : @
    sed -i.bak -E "s$(printf '\x01')^${key}=.*$(printf '\x01')${key}=${value}$(printf '\x01')" "$file"
    rm -f "$file.bak"
  else
    echo "${key}=${value}" >> "$file"
  fi
}

ensure_deps_env() {
  # infra/docker/.env: ports + generated passwords for the dependency containers (gitignored).
  if [ ! -f "$DEPS_ENV" ]; then
    umask 077
    cat > "$DEPS_ENV" <<EOF
# GPU Deck dev dependencies (infra/docker/docker-compose.deps.yml). Generated by
# infra/scripts/bootstrap.dev.sh; gitignored. bootstrap copies the connection values
# into apps/fastapi/.env.
EOF
    umask 022
    print_success "created infra/docker/.env"
  fi
  local key default
  while read -r key default; do
    if [ -z "$(deps_get "$key")" ]; then
      [ "$default" = "@random" ] && default="$(openssl rand -hex 24)"
      _file_set "$DEPS_ENV" "$key" "$default"
    fi
  done <<EOF
GPUDECK_DEPS_PG_PORT 55432
GPUDECK_DEPS_PG_SUPERUSER_PASSWORD @random
GPUDECK_DEPS_PG_USER gpu_deck
GPUDECK_DEPS_PG_PASSWORD @random
GPUDECK_DEPS_PG_DB gpu_deck_dev
GPUDECK_DEPS_REDIS_PORT 56379
GPUDECK_DEPS_REDIS_USER gpu-deck
GPUDECK_DEPS_REDIS_PASSWORD @random
GPUDECK_PROXY_HTTPS_PORT 58443
EOF
  chmod 600 "$DEPS_ENV"
}

wait_healthy() {  # wait_healthy SERVICE [TIMEOUT_SECONDS]
  local svc="$1" timeout="${2:-90}" cid status waited=0
  cid=$(dc ps -q "$svc" 2>/dev/null)
  [ -n "$cid" ] || { print_error "$svc container not found"; return 1; }
  while :; do
    status=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo missing)
    case "$status" in
      healthy|running) print_success "$svc is $status"; return 0 ;;
      unhealthy|exited|dead|missing) print_error "$svc is $status — see: docker compose -f infra/docker/docker-compose.deps.yml logs $svc"; return 1 ;;
    esac
    [ "$waited" -ge "$timeout" ] && { print_error "$svc not healthy after ${timeout}s (last: $status)"; return 1; }
    sleep 2; waited=$((waited + 2))
  done
}

deps_up() {
  print_step "Dependencies (Docker: Postgres + Redis)"
  require_docker
  ensure_deps_env
  dc up -d postgres redis
  wait_healthy postgres
  wait_healthy redis
  # Idempotent: (re)creates the app role/database/extensions and syncs the role password.
  dc exec -T postgres /docker-entrypoint-initdb.d/10-gpu-deck.sh >/dev/null
  print_success "Postgres 127.0.0.1:$(deps_get GPUDECK_DEPS_PG_PORT) db $(deps_get GPUDECK_DEPS_PG_DB) (role $(deps_get GPUDECK_DEPS_PG_USER))"
  print_success "Redis    127.0.0.1:$(deps_get GPUDECK_DEPS_REDIS_PORT) user $(deps_get GPUDECK_DEPS_REDIS_USER) (keys ${REDIS_PREFIX}:*)"
}

deps_down() {
  print_step "Dependencies: stopping containers (volumes kept)"
  require_docker
  [ -f "$DEPS_ENV" ] || ensure_deps_env
  dc down
}

deps_status() {
  print_step "Dependencies (compose project gpu-deck-deps)"
  if ! docker info >/dev/null 2>&1; then
    print_info "  Docker engine not running"
    return 0
  fi
  [ -f "$DEPS_ENV" ] || { print_info "  infra/docker/.env missing — run: $0 deps up"; return 0; }
  dc ps
}

deps_reset() {
  if [ "${1:-}" != "--yes" ]; then
    printf "This deletes the dev Postgres + Redis data (volumes gpu-deck-deps_*). Continue? [y/N] "
    read -r answer
    case "$answer" in y|Y|yes) ;; *) print_info "aborted"; return 0 ;; esac
  fi
  require_docker
  [ -f "$DEPS_ENV" ] || ensure_deps_env
  dc down -v
  print_success "volumes removed"
  deps_up
}

cmd_deps() {
  local sub="${1:-status}"
  shift || true
  case "$sub" in
    up)     deps_up ;;
    down)   deps_down ;;
    status) deps_status ;;
    reset)  deps_reset "$@" ;;
    *) print_error "Unknown deps command: $sub (up|down|status|reset)"; exit 1 ;;
  esac
}

ensure_proxy() {
  print_step "Caddy HTTPS proxy (compose profile proxy)"
  require_docker
  ensure_deps_env
  load_env
  ADMIN_PORT="$PORT" API_LAYER_PORT="$API_LAYER_PORT" WEB_PORT="$WEB_PORT" dc up -d caddy
  local p; p=$(deps_get GPUDECK_PROXY_HTTPS_PORT)
  print_success "https://gpu-deck.localhost:${p} (web), https://gpu-deck-api.localhost:${p} (serving), https://gpu-deck-admin.localhost:${p} (admin)"
  print_info "  certificates come from Caddy's internal CA; trust it with:"
  print_info "  docker compose -f infra/docker/docker-compose.deps.yml cp caddy:/data/caddy/pki/authorities/local/root.crt ./gpu-deck-caddy-root.crt"
}

# ---------- .env ----------

_set_env() { _file_set "$ENV_FILE" "$1" "$2"; }

ensure_env() {
  print_step "apps/fastapi/.env"
  if [ ! -f "$ENV_FILE" ]; then
    cp "$FASTAPI_DIR/.env.example" "$ENV_FILE"
    print_success "created .env from .env.example"
  fi

  # Connection values from infra/docker/.env (other settings are left alone).
  local pg_port pg_user pg_pass pg_db pg_su r_port r_user r_pass
  pg_port=$(deps_get GPUDECK_DEPS_PG_PORT); pg_user=$(deps_get GPUDECK_DEPS_PG_USER)
  pg_pass=$(deps_get GPUDECK_DEPS_PG_PASSWORD); pg_db=$(deps_get GPUDECK_DEPS_PG_DB)
  pg_su=$(deps_get GPUDECK_DEPS_PG_SUPERUSER_PASSWORD)
  r_port=$(deps_get GPUDECK_DEPS_REDIS_PORT); r_user=$(deps_get GPUDECK_DEPS_REDIS_USER)
  r_pass=$(deps_get GPUDECK_DEPS_REDIS_PASSWORD)

  _set_env POSTGRES_HOST 127.0.0.1
  _set_env POSTGRES_PORT "$pg_port"
  _set_env POSTGRES_USER "$pg_user"
  _set_env POSTGRES_PASSWORD "$pg_pass"
  _set_env POSTGRES_DB "$pg_db"
  _set_env DATABASE_URL "postgresql://${pg_user}:${pg_pass}@127.0.0.1:${pg_port}/${pg_db}"
  # Not an app setting: integration tests that need CREATE DATABASE use the container superuser.
  _set_env TEST_PG_ADMIN_URL "postgresql://postgres:${pg_su}@127.0.0.1:${pg_port}/postgres"
  print_success "Postgres settings written (127.0.0.1:${pg_port}/${pg_db})"

  _set_env REDIS_HOST 127.0.0.1
  _set_env REDIS_PORT "$r_port"
  _set_env REDIS_DB 0
  _set_env REDIS_USERNAME "$r_user"
  _set_env REDIS_PASSWORD "$r_pass"
  _set_env REDIS_URL "redis://${r_user}:${r_pass}@127.0.0.1:${r_port}/0"
  _set_env REDIS_KEY_PREFIX "${REDIS_PREFIX}:"
  print_success "Redis settings written (127.0.0.1:${r_port}, keys ${REDIS_PREFIX}:*)"

  # Secrets
  if grep -qE '^SECRET_KEY=.*CHANGE-ME' "$ENV_FILE"; then
    _set_env SECRET_KEY "$(openssl rand -hex 32)"
    print_success "generated SECRET_KEY"
  fi
  if grep -qE '^VAULT_KEYS=.*CHANGE-ME' "$ENV_FILE"; then
    _set_env VAULT_KEYS "$(openssl rand -base64 32 | tr '+/' '-_')"
    print_success "generated VAULT_KEYS"
  fi
  if grep -qE '^ADMIN_PASSWORD=.*CHANGE-ME' "$ENV_FILE"; then
    _set_env ADMIN_PASSWORD "${ADMIN_PASSWORD:-Admin@GpuDeck2026}"
    print_success "set ADMIN_PASSWORD (change it in .env)"
  fi
  load_env
}


//! Certificate rotation (`rotate_cert` → CSR, `install_cert` → store + reconnect) and expiry
//! warnings (`cert_expiring`).

use std::sync::Arc;
use std::time::Duration;

use gpudeck_protocol::{
    error_code, ErrorInfo, Event, EventKind, InstallCertArgs, JsonObject, RotateCertArgs,
};
use serde_json::{json, Value};

use crate::agent::Agent;

/// Warn this long before `not_after`.
pub const EXPIRY_WARNING_DAYS: i64 = 30;

pub async fn rotate(agent: &Arc<Agent>, a: RotateCertArgs) -> Result<Value, ErrorInfo> {
    let key = crate::pki::generate_key(a.key_type)
        .map_err(|e| ErrorInfo::new(error_code::INVALID_ARGS, format!("{e:#}")))?;
    let host = crate::system::host_info();
    let sans = crate::join::proxy_sans(
        &host.hostname,
        &host.ip_addresses,
        agent.cfg.proxy_address.as_deref(),
    );
    let csr = crate::pki::build_csr_with_sans(&key, &agent.node_id.to_string(), &sans)
        .map_err(|e| ErrorInfo::new(error_code::INTERNAL, format!("{e:#}")))?;
    crate::state::write_private(
        &agent.paths.pending_key(),
        key.serialize_pem().as_bytes(),
        0o600,
    )
    .map_err(|e| ErrorInfo::new(error_code::INTERNAL, format!("{e:#}")))?;
    tracing::info!(reason = ?a.reason, "generated a new key pair for certificate rotation");
    Ok(json!({"csr_pem": csr, "key_type": a.key_type}))
}

pub async fn install(agent: &Arc<Agent>, a: InstallCertArgs) -> Result<Value, ErrorInfo> {
    let bad = |m: String| ErrorInfo::new(error_code::INVALID_ARGS, m);
    let key_pem = std::fs::read_to_string(agent.paths.pending_key())
        .map_err(|_| bad("no pending key: send rotate_cert first".into()))?;
    let key = crate::pki::parse_key_pem(&key_pem).map_err(|e| bad(format!("{e:#}")))?;
    if !crate::pki::cert_matches_key(&a.certificate_pem, &key).map_err(|e| bad(format!("{e:#}")))? {
        return Err(bad(
            "certificate does not match the key generated by rotate_cert".into(),
        ));
    }
    let certs =
        crate::pki::parse_cert_bundle(&a.certificate_pem).map_err(|e| bad(format!("{e:#}")))?;
    let info = crate::pki::inspect_cert(&certs[0]).map_err(|e| bad(format!("{e:#}")))?;
    if info.common_name.as_deref() != Some(agent.node_id.to_string().as_str()) {
        return Err(bad(format!(
            "certificate CN {:?} != node_id {}",
            info.common_name, agent.node_id
        )));
    }
    crate::pki::parse_cert_bundle(&a.ca_bundle_pem)
        .map_err(|e| bad(format!("ca_bundle_pem: {e:#}")))?;
    // The new identity must build a valid client config before anything is replaced.
    let id = crate::tls::Identity::from_pems(&key_pem, &a.certificate_pem, &a.ca_bundle_pem)
        .map_err(|e| bad(format!("{e:#}")))?;
    id.hub_client_config().map_err(|e| bad(format!("{e:#}")))?;
    crate::tls::store_identity(&agent.paths, &key_pem, &a.certificate_pem, &a.ca_bundle_pem)
        .map_err(|e| ErrorInfo::new(error_code::INTERNAL, format!("{e:#}")))?;
    let _ = std::fs::remove_file(agent.paths.pending_key());
    let fp = id.fingerprint();
    *agent.identity.write().unwrap_or_else(|e| e.into_inner()) = Arc::new(id);
    agent.proxy.invalidate_tls();
    let mut d = JsonObject::new();
    d.insert("fingerprint_sha256".into(), fp.clone().into());
    d.insert("serial".into(), a.serial.clone().into());
    d.insert("not_after".into(), a.not_after.to_rfc3339().into());
    agent.event(
        Event::info(
            EventKind::CertRotated,
            format!("node certificate rotated (serial {})", a.serial),
        )
        .details(d),
    );
    // Reconnect with the new certificate once this result has been written.
    let ag = agent.clone();
    tokio::spawn(async move {
        tokio::time::sleep(Duration::from_millis(1500)).await;
        ag.reconnect.notify_one();
    });
    Ok(json!({"fingerprint_sha256": fp, "not_after": a.not_after}))
}

pub fn check_expiry(agent: &Agent) {
    let info = agent.identity().info.clone();
    let left = info.not_after - chrono::Utc::now();
    if left.num_days() < EXPIRY_WARNING_DAYS {
        let mut d = JsonObject::new();
        d.insert("not_after".into(), info.not_after.to_rfc3339().into());
        d.insert("days_left".into(), left.num_days().into());
        d.insert("serial".into(), info.serial_hex.into());
        let sev = if left.num_days() < 3 {
            gpudeck_protocol::Severity::Critical
        } else {
            gpudeck_protocol::Severity::Warning
        };
        agent.event(
            Event::new(
                EventKind::CertExpiring,
                sev,
                format!("node certificate expires in {} days", left.num_days()),
            )
            .details(d),
        );
    }
}

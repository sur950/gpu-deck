const GROUPS: { value: BillingGroupKey; label: string }[] = [
  { value: 'api_key', label: 'API key' },
  { value: 'model', label: 'Model' },
  { value: 'node', label: 'Node' },
  { value: 'cluster', label: 'Cluster' },
  { value: 'deployment', label: 'Deployment' },
];

export const REPORT_STATUS: Record<BillingReport['status'], { label: string; badge: 'pending' | 'loading' | 'completed' | 'failed' }> = {
  pending: { label: 'Queued', badge: 'pending' },
  generating: { label: 'Generating', badge: 'loading' },
  ready: { label: 'Ready', badge: 'completed' },
  failed: { label: 'Failed', badge: 'failed' },
};

function monthRange(offset: number): { start: string; end: string; label: string } {
  const now = new Date();
  const start = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + offset, 1));
  const end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + offset + 1, 1));
  return { start: start.toISOString(), end: end.toISOString(), label: start.toLocaleString('en-US', { month: 'long', year: 'numeric', timeZone: 'UTC' }) };
}

export async function exportReport(r: BillingReport) {
  try {
    await downloadFromApi(billingReportExportPath(r.id), `${r.name.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}.csv`);
    toast.success('Report exported');
  } catch (err) {
    toast.error(err instanceof Error ? err.message : 'Export failed');
  }
}

function NewReportDialog({ open, onOpenChange }: { open: boolean; onOpenChange: (o: boolean) => void }) {
  const router = useRouter();
  const create = useCreateBillingReport();
  const [period, setPeriod] = useState<'last' | 'this' | 'custom'>('last');
  const [from, setFrom] = useState('');
  const [to, setTo] = useState('');
  const [groups, setGroups] = useState<BillingGroupKey[]>(['api_key', 'model']);
  const preset = period === 'custom' ? null : monthRange(period === 'last' ? -1 : 0);
  const [name, setName] = useState('');
  const start = preset ? preset.start : from ? new Date(`${from}T00:00:00Z`).toISOString() : '';
  const end = preset ? preset.end : to ? new Date(`${to}T00:00:00Z`).toISOString() : '';
  const effectiveName = name.trim() || (preset ? `${preset.label}${period === 'this' ? ' — month to date' : ''}` : from && to ? `${from} to ${to}` : '');
  const invalid = !start || !end || end <= start || groups.length === 0 || !effectiveName;

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-lg">
        <DialogHeader>
          <DialogTitle>New billing report</DialogTitle>
          <DialogDescription>Totals and cost per group for a period, generated by the jobs process and exportable as CSV.</DialogDescription>
        </DialogHeader>
        <div className="space-y-4">
          <div className="space-y-1.5 text-xs font-medium">
            Period
            <Segmented value={period} onChange={setPeriod} options={[{ value: 'last', label: monthRange(-1).label }, { value: 'this', label: 'This month so far' }, { value: 'custom', label: 'Custom' }]} aria-label="Period" />
          </div>
          {period === 'custom' && (
            <div className="grid gap-3 sm:grid-cols-2">
              <label className="space-y-1.5 text-xs font-medium">
                From (UTC)
                <Input type="date" value={from} onChange={(e) => setFrom(e.target.value)} />
              </label>
              <label className="space-y-1.5 text-xs font-medium">
                To (exclusive)
                <Input type="date" value={to} onChange={(e) => setTo(e.target.value)} />
              </label>
            </div>
          )}
          <div className="space-y-1.5 text-xs font-medium">
            Group lines by
            <div className="flex flex-wrap gap-1.5">
              {GROUPS.map((g) => {
                const on = groups.includes(g.value);
                return (
                  <button key={g.value} type="button" aria-pressed={on} onClick={() => setGroups(on ? groups.filter((x) => x !== g.value) : [...groups, g.value])} className={cn('h-7 rounded-full border px-3 text-xs font-normal outline-none focus-visible:ring-2 focus-visible:ring-ring/30', on ? 'border-foreground/30 bg-foreground/[0.06] text-foreground' : 'border-border text-muted-foreground hover:text-foreground')}>
                    {g.label}
                  </button>
                );
              })}
            </div>
          </div>
          <label className="block space-y-1.5 text-xs font-medium">
            Name
            <Input value={name} onChange={(e) => setName(e.target.value)} placeholder={effectiveName || 'Report name'} />
          </label>
        </div>
        <DialogFooter>
          <Button variant="outline" size="sm" onClick={() => onOpenChange(false)}>
            Cancel
          </Button>
          <Button
            size="sm"
            disabled={invalid || create.isPending}
            onClick={() =>
              create.mutate({ name: effectiveName, period_start: start, period_end: end, group_by: groups }, { onSuccess: (r) => { onOpenChange(false); router.push(`/billing/reports/${r.id}`); } })
            }
          >
            {create.isPending && <Loader2 className="size-4 animate-spin" />}
            Generate report
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

export function ReportsTab() {
  const [pending, setPending] = useState(false);
  const reports = useBillingReports({ pageSize: 50 }, { refetchInterval: pending ? 2_000 : false });
  const regenerate = useRegenerateBillingReport();
  const del = useDeleteBillingReport();
  const [open, setOpen] = useState(false);
  const [deleting, setDeleting] = useState<BillingReport | null>(null);
  const items = reports.data?.items ?? [];
  const anyPending = items.some((r) => r.status === 'pending' || r.status === 'generating');
  if (anyPending !== pending) setPending(anyPending);

  if (reports.isError) return <ErrorState title="Could not load reports" onRetry={() => void reports.refetch()} />;

  return (
    <Card className="rounded-md shadow-premium">
      <CardHeader className="flex flex-row items-center justify-between">
        <div className="space-y-0.5">
          <CardTitle className="text-sm font-semibold">Monthly reports</CardTitle>
          <CardDescription>Frozen totals per period — what you send to finance.</CardDescription>
        </div>
        <Button size="sm" className="rounded-sm" onClick={() => setOpen(true)}>
          <Plus className="size-4" /> New report
        </Button>
      </CardHeader>
      <CardContent>
        {reports.isLoading ? (
          <Skeleton className="h-40" />
        ) : items.length === 0 ? (
          <EmptyState icon={FileText} title="No reports yet" description="Generate last month’s report to see cost per key and model." />
        ) : (
          <div className="overflow-x-auto">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Report</TableHead>
                  <TableHead>Period (UTC)</TableHead>
                  <TableHead>Grouped by</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead className="text-right">Total</TableHead>
                  <TableHead>Generated</TableHead>
                  <TableHead className="w-10" />
                </TableRow>
              </TableHeader>
              <TableBody>
                {items.map((r) => {
                  const st = REPORT_STATUS[r.status];
                  return (
                    <TableRow key={r.id}>
                      <TableCell>
                        <Link href={`/billing/reports/${r.id}`} className="text-[13px] font-semibold hover:underline">
                          {r.name}
                        </Link>
                        {r.errorMessage && <p className="max-w-[320px] truncate text-[11px] text-error-dark dark:text-error-light">{r.errorMessage}</p>}
                      </TableCell>
                      <TableCell className="whitespace-nowrap text-xs tabular-nums">
                        {new Date(r.periodStart).toLocaleDateString(undefined, { timeZone: 'UTC' })} – {new Date(Date.parse(r.periodEnd) - 1).toLocaleDateString(undefined, { timeZone: 'UTC' })}
                      </TableCell>
                      <TableCell className="text-xs text-muted-foreground">{r.groupBy.map((g) => GROUPS.find((x) => x.value === g)?.label ?? g).join(', ')}</TableCell>
                      <TableCell>
                        <StatusBadge variant={st.badge}>
                          {(r.status === 'pending' || r.status === 'generating') && <Loader2 className="mr-1 size-3 animate-spin" />}
                          {st.label}
                        </StatusBadge>
                      </TableCell>
                      <TableCell className="text-right text-xs font-semibold tabular-nums">{r.totals ? fmtUsd(r.totals.costUsd) : '—'}</TableCell>
                      <TableCell className="text-xs text-muted-foreground">{r.generatedAt ? <RelativeTime value={r.generatedAt} /> : '—'}</TableCell>
                      <TableCell>
                        <DropdownMenu>
                          <DropdownMenuTrigger render={<Button variant="ghost" size="icon-sm" aria-label={`Actions for ${r.name}`} />}>
                            <MoreVertical className="size-4" />
                          </DropdownMenuTrigger>
                          <DropdownMenuContent align="end" className="w-44">
                            <DropdownMenuItem disabled={r.status !== 'ready'} onClick={() => void exportReport(r)}>
                              <Download className="size-4" /> Export CSV
                            </DropdownMenuItem>
                            <DropdownMenuItem onClick={() => regenerate.mutate(r.id)}>
                              <RefreshCw className="size-4" /> Regenerate
                            </DropdownMenuItem>
                            <DropdownMenuSeparator />
                            <DropdownMenuItem className="text-destructive" onClick={() => setDeleting(r)}>
                              <Trash2 className="size-4" /> Delete
                            </DropdownMenuItem>
                          </DropdownMenuContent>
                        </DropdownMenu>
                      </TableCell>
                    </TableRow>
                  );
                })}
              </TableBody>
            </Table>
          </div>
        )}
      </CardContent>
      {open && <NewReportDialog open={open} onOpenChange={setOpen} />}
      <DeleteConfirmationDialog
        open={!!deleting}
        onOpenChange={(o) => !o && setDeleting(null)}
        itemName={deleting?.name ?? ''}
        resourceType="report"
        warningMessage="Usage data is not affected — the report can be generated again."
        isDeleting={del.isPending}
        onConfirm={() => {
          if (deleting) del.mutate(deleting.id, { onSuccess: () => setDeleting(null) });
        }}
      />
    </Card>
  );
}

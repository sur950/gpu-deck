"""
cloud-init / startup script that turns a fresh GPU VM into a GPU Deck node.

The script (bash, accepted as user-data by AWS / Azure custom data /
DigitalOcean and as ``startup-script`` metadata by GCP):

1. trusts the hub through the internal CA certificate embedded in the script
   (falls back to the system trust store when the hub presents a public cert),
2. downloads the agent for the VM's target triple from the hub download
   endpoint ``/agent/v1/downloads/{version}/{target}`` (authorised by the
   join token in ``X-GPUDeck-Join-Token``, which is still unused at that point)
   and checks its SHA-256 (``X-Checksum-Sha256`` header, else ``.../sha256``),
3. installs ``/usr/local/bin/gpudeck-agent``, the ``gpudeck`` user (GPU device
   groups) and the hardened systemd unit from apps/node-agent/packaging,
4. joins with the one-time token minted for this VM (``--ca-fingerprint`` pins
   the CA; serving mode tunnel, so the VM needs no inbound port), applies the host
   firewall for the agent's ports and starts the service.

It is idempotent: on later boots (GCP re-runs startup scripts) it only makes
sure the service runs. The join token is single use and expires after
``CLOUD_JOIN_TOKEN_TTL_MINUTES``; it is the only secret in the script.
"""

from __future__ import annotations

import shlex
from dataclasses import dataclass, field
from typing import Dict, Optional

from app.core.logger import get_logger
from app.core.settings import settings

logger = get_logger(__name__)

SYSTEMD_UNIT = """[Unit]
Description=GPU Deck node agent
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
User=gpudeck
Group=gpudeck
SupplementaryGroups=video render
ExecStart=/usr/local/bin/gpudeck-agent --config /etc/gpudeck/agent.toml --log-json run
Restart=always
RestartSec=5
KillMode=mixed
TimeoutStopSec=60
LimitNOFILE=65536
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
ReadWritePaths=/var/lib/gpudeck /etc/gpudeck
StateDirectory=gpudeck
StateDirectoryMode=0700
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
LockPersonality=yes
DeviceAllow=/dev/nvidiactl rw
DeviceAllow=/dev/nvidia-uvm rw
DeviceAllow=char-nvidia-frontend rw
DeviceAllow=/dev/kfd rw
DeviceAllow=char-drm rw
# Host firewall for the agent's ports, kept current by the agent (agent protocol §13).
AmbientCapabilities=CAP_NET_ADMIN
CapabilityBoundingSet=CAP_NET_ADMIN

[Install]
WantedBy=multi-user.target
"""

TEMPLATE = r"""#!/bin/bash
# GPU Deck node bootstrap, generated by the control plane for cloud instance __INSTANCE_ID__
# (__PROVIDER__). Installs the node agent and joins it to the hub with a one-time token.
set -euo pipefail
exec >>/var/log/gpudeck-bootstrap.log 2>&1
echo "gpu-deck bootstrap start $(date -u +%FT%TZ)"

HUB_URL=__HUB_URL__
DOWNLOAD_BASE=__DOWNLOAD_BASE__
AGENT_VERSION=__AGENT_VERSION__
JOIN_TOKEN=__JOIN_TOKEN__
CA_FINGERPRINT=__CA_FINGERPRINT__
NODE_NAME=__NODE_NAME__
LABELS=(__LABELS__)
STATE_DIR=/var/lib/gpudeck
CONFIG=/etc/gpudeck/agent.toml

if [[ -f "$STATE_DIR/.gpudeck-joined" ]]; then
  systemctl enable --now gpudeck-agent.service || true
  echo "already joined; agent service ensured"
  exit 0
fi

install -d -m 0755 /etc/gpudeck
cat >/etc/gpudeck/hub-ca.pem <<'GPUDECK_CA'
__CA_PEM__
GPUDECK_CA

case "$(uname -m)" in
  x86_64|amd64) TARGET=x86_64-unknown-linux-gnu ;;
  aarch64|arm64) TARGET=aarch64-unknown-linux-gnu ;;
  *) echo "unsupported architecture $(uname -m)"; exit 1 ;;
esac
URL="$DOWNLOAD_BASE/agent/v1/downloads/$AGENT_VERSION/$TARGET"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

fetch() {  # fetch URL OUT [HEADERS_OUT]: internal CA first, then the system trust store
  local hdr="${3:-/dev/null}" try
  for try in $(seq 1 30); do
    if curl -fsSL --cacert /etc/gpudeck/hub-ca.pem -H "X-GPUDeck-Join-Token: $JOIN_TOKEN" \
        -D "$hdr" "$1" -o "$2" \
      || curl -fsSL -H "X-GPUDeck-Join-Token: $JOIN_TOKEN" -D "$hdr" "$1" -o "$2"; then
      return 0
    fi
    sleep 10
  done
  return 1
}

fetch "$URL" "$WORK/download" "$WORK/headers"
EXPECTED="$(grep -i '^x-checksum-sha256:' "$WORK/headers" | tail -1 | awk '{print $2}' \
  | tr -d '\r' || true)"
if [[ -z "$EXPECTED" ]] && fetch "$URL/sha256" "$WORK/download.sha256"; then
  EXPECTED="$(awk '{print $1}' "$WORK/download.sha256")"
fi
if [[ -z "$EXPECTED" ]]; then echo "no checksum published for $URL"; exit 1; fi
ACTUAL="$(sha256sum "$WORK/download" | awk '{print $1}')"
if [[ "$ACTUAL" != "$EXPECTED" ]]; then echo "checksum mismatch for $URL"; exit 1; fi

if gzip -t "$WORK/download" 2>/dev/null; then
  tar -C "$WORK" -xzf "$WORK/download"
  BIN="$(find "$WORK" -type f -name gpudeck-agent | head -1)"
else
  BIN="$WORK/download"
fi
install -m 0755 "$BIN" /usr/local/bin/gpudeck-agent

id gpudeck >/dev/null 2>&1 \
  || useradd --system --home-dir "$STATE_DIR" --shell /usr/sbin/nologin gpudeck
for g in video render; do getent group "$g" >/dev/null && usermod -aG "$g" gpudeck; done
install -d -o gpudeck -g gpudeck -m 0750 "$STATE_DIR" "$STATE_DIR/cache"

JOIN=(/usr/local/bin/gpudeck-agent --config "$CONFIG" join --url "$HUB_URL" --token "$JOIN_TOKEN"
      --ca-fingerprint "$CA_FINGERPRINT" --name "$NODE_NAME" --state-dir "$STATE_DIR")
for l in "${LABELS[@]}"; do JOIN+=(--label "$l"); done
"${JOIN[@]}"
chown -R gpudeck:gpudeck "$STATE_DIR" /etc/gpudeck
# Agent ports closed to everyone but the API layer (tunnel mode: nothing listens at all); the
# ports sshd listens on stay open.
if command -v nft >/dev/null 2>&1; then
  /usr/local/bin/gpudeck-agent --config "$CONFIG" firewall apply \
    || echo "host firewall not applied (see above); the cloud security group still applies"
fi
touch "$STATE_DIR/.gpudeck-joined"

cat >/etc/systemd/system/gpudeck-agent.service <<'GPUDECK_UNIT'
__SYSTEMD_UNIT__GPUDECK_UNIT
systemctl daemon-reload
systemctl enable --now gpudeck-agent.service
# Self-update helper (agent protocol 14): applies staged, signature-verified releases.
/usr/local/bin/gpudeck-agent --config "$CONFIG" update install-helper \
  || echo "update helper not installed"
echo "gpu-deck bootstrap done $(date -u +%FT%TZ)"
"""


@dataclass
class BootstrapParams:
    instance_id: str
    provider: str
    join_token: str
    ca_fingerprint: str
    ca_pem: str
    node_name: str
    labels: Dict[str, str] = field(default_factory=dict)
    hub_url: Optional[str] = None
    download_base: Optional[str] = None
    agent_version: Optional[str] = None


def download_base_url() -> str:
    return (settings.CLOUD_AGENT_DOWNLOAD_BASE_URL or settings.AGENT_HUB_PUBLIC_URL).rstrip("/")


def render_bootstrap(params: BootstrapParams) -> str:
    """The bash bootstrap for one VM. Every value is shell-quoted."""
    labels = " ".join(shlex.quote(f"{k}={v}") for k, v in sorted(params.labels.items()))
    replacements = {
        "__INSTANCE_ID__": _comment_safe(params.instance_id),
        "__PROVIDER__": _comment_safe(params.provider),
        "__HUB_URL__": shlex.quote((params.hub_url or settings.AGENT_HUB_PUBLIC_URL).rstrip("/")),
        "__DOWNLOAD_BASE__": shlex.quote(params.download_base or download_base_url()),
        "__AGENT_VERSION__": shlex.quote(params.agent_version or settings.CLOUD_AGENT_VERSION),
        "__JOIN_TOKEN__": shlex.quote(params.join_token),
        "__CA_FINGERPRINT__": shlex.quote(params.ca_fingerprint),
        "__NODE_NAME__": shlex.quote(params.node_name),
        "__LABELS__": labels,
        "__CA_PEM__": params.ca_pem.strip(),
        "__SYSTEMD_UNIT__": SYSTEMD_UNIT,
    }
    script = TEMPLATE
    for key, value in replacements.items():
        script = script.replace(key, value)
    return script


def _comment_safe(value: str) -> str:
    return "".join(ch for ch in str(value) if ch.isalnum() or ch in "-_.:")
